// Command protoc-gen-minirpc generates type-safe Mini-RPC client and server
// adapters for unary service definitions.
package main

import (
	"fmt"
	"strconv"
	"strings"
	"unicode"
	"unicode/utf8"

	"google.golang.org/protobuf/compiler/protogen"
)

const rpcImportPath = protogen.GoImportPath("github.com/zjsycwmrbig/mini-rpc/pkg/rpc")

func main() {
	protogen.Options{}.Run(func(plugin *protogen.Plugin) error {
		for _, file := range plugin.Files {
			if file.Generate {
				if err := generateFile(plugin, file); err != nil {
					return err
				}
			}
		}
		return nil
	})
}

func generateFile(plugin *protogen.Plugin, file *protogen.File) error {
	if len(file.Services) == 0 {
		return nil
	}

	for _, service := range file.Services {
		for _, method := range service.Methods {
			if method.Desc.IsStreamingClient() || method.Desc.IsStreamingServer() {
				return fmt.Errorf("%s.%s: streaming RPC is not supported by Mini-RPC v1", service.Desc.FullName(), method.Desc.Name())
			}
		}
	}

	generated := plugin.NewGeneratedFile(file.GeneratedFilenamePrefix+"_minirpc.pb.go", file.GoImportPath)
	generated.P("// Code generated by protoc-gen-minirpc. DO NOT EDIT.")
	generated.P("// source: ", file.Desc.Path())
	generated.P()
	generated.P("package ", file.GoPackageName)
	generated.P()
	generated.P("import (")
	generated.P(strconv.Quote("context"))
	generated.P()
	generated.P(strconv.Quote("google.golang.org/protobuf/proto"))
	generated.P()
	generated.P("rpc ", strconv.Quote(string(rpcImportPath)))
	generated.P(")")

	for _, service := range file.Services {
		generateService(generated, service)
	}
	return nil
}

func generateService(generated *protogen.GeneratedFile, service *protogen.Service) {
	serviceName := service.Desc.FullName()
	clientType := lowerFirst(service.GoName) + "Client"

	generated.P()
	generated.P("// ", service.GoName, "ServiceName is the fully qualified service name used on the wire.")
	generated.P("const ", service.GoName, "ServiceName = ", strconv.Quote(string(serviceName)))
	generated.P()
	generated.P("// ", service.GoName, "Server is the server API for ", serviceName, ".")
	generated.P("type ", service.GoName, "Server interface {")
	for _, method := range service.Methods {
		generated.P(method.GoName, "(ctx context.Context, request *", generated.QualifiedGoIdent(method.Input.GoIdent), ") (*", generated.QualifiedGoIdent(method.Output.GoIdent), ", error)")
	}
	generated.P("}")

	generated.P()
	generated.P("// ", service.GoName, "Client is the generated client API for ", serviceName, ".")
	generated.P("type ", service.GoName, "Client interface {")
	for _, method := range service.Methods {
		generated.P(method.GoName, "(ctx context.Context, request *", generated.QualifiedGoIdent(method.Input.GoIdent), ") (*", generated.QualifiedGoIdent(method.Output.GoIdent), ", error)")
	}
	generated.P("}")

	generated.P()
	generated.P("type ", clientType, " struct {")
	generated.P("clientConn rpc.ClientConn")
	generated.P("}")

	generated.P()
	generated.P("// New", service.GoName, "Client creates a generated client backed by clientConn.")
	generated.P("func New", service.GoName, "Client(clientConn rpc.ClientConn) ", service.GoName, "Client {")
	generated.P("return &", clientType, "{clientConn: clientConn}")
	generated.P("}")

	for _, method := range service.Methods {
		inputType := generated.QualifiedGoIdent(method.Input.GoIdent)
		outputType := generated.QualifiedGoIdent(method.Output.GoIdent)
		generated.P()
		generated.P("func (client *", clientType, ") ", method.GoName, "(ctx context.Context, request *", inputType, ") (*", outputType, ", error) {")
		generated.P("response := new(", outputType, ")")
		generated.P("if err := client.clientConn.Invoke(ctx, ", service.GoName, "ServiceName, ", strconv.Quote(method.GoName), ", request, response); err != nil {")
		generated.P("return nil, err")
		generated.P("}")
		generated.P("return response, nil")
		generated.P("}")
	}

	for _, method := range service.Methods {
		inputType := generated.QualifiedGoIdent(method.Input.GoIdent)
		generated.P()
		generated.P("func _", service.GoName, "_", method.GoName, "_Handler(implementation any, ctx context.Context, request proto.Message) (proto.Message, error) {")
		generated.P("return implementation.(", service.GoName, "Server).", method.GoName, "(ctx, request.(*", inputType, "))")
		generated.P("}")
	}

	generated.P()
	generated.P("// ", service.GoName, "ServiceDesc is the method table used by the server dispatcher.")
	generated.P("var ", service.GoName, "ServiceDesc = rpc.ServiceDesc{")
	generated.P("ServiceName: ", service.GoName, "ServiceName,")
	generated.P("HandlerType: (*", service.GoName, "Server)(nil),")
	generated.P("Methods: []rpc.MethodDesc{")
	for _, method := range service.Methods {
		generated.P("{")
		generated.P("MethodName: ", strconv.Quote(method.GoName), ",")
		generated.P("Handler: _", service.GoName, "_", method.GoName, "_Handler,")
		generated.P("NewRequest: func() proto.Message { return new(", generated.QualifiedGoIdent(method.Input.GoIdent), ") },")
		generated.P("},")
	}
	generated.P("},")
	generated.P("}")

	generated.P()
	generated.P("// Register", service.GoName, "Server registers implementation with registrar.")
	generated.P("func Register", service.GoName, "Server(registrar rpc.ServiceRegistrar, implementation ", service.GoName, "Server) error {")
	generated.P("return registrar.RegisterService(&", service.GoName, "ServiceDesc, implementation)")
	generated.P("}")
}

func lowerFirst(value string) string {
	first, size := utf8.DecodeRuneInString(value)
	if first == utf8.RuneError || size == 0 {
		return strings.ToLower(value)
	}
	return string(unicode.ToLower(first)) + value[size:]
}
